#!/usr/bin/env python3
"""CT40.A9.Solari.build_embedded.py

Browsers refuse to let a page opened by double-click (file://) read neighbouring
.json / .wav files. So the HTML first tries to read the real JSON files, and if
the browser blocks that it falls back to CT40.A9.Solari.embedded.js, which this
script writes: a copy of both JSON files plus the clack sample as base64.

Re-run after editing either JSON file or replacing audio/one.wav:
    python3 CT40.A9.Solari.build_embedded.py
(Or skip it: serve the folder with CT40.A9.Solari.serve.sh, or use the page's
"Load JSON" button, and the edited files are read directly.)
"""
import base64, json, os

HERE = os.path.dirname(os.path.abspath(__file__))

def load(name):
    with open(os.path.join(HERE, name)) as f:
        return json.load(f)

fields = load("CT40.A9.Solari.fields.json")
schedule = load("CT40.A9.Solari.schedule.json")
wav_path = os.path.join(HERE, fields.get("sound", {}).get("file", "audio/one.wav"))
with open(wav_path, "rb") as f:
    wav_b64 = base64.b64encode(f.read()).decode("ascii")

out = os.path.join(HERE, "CT40.A9.Solari.embedded.js")
with open(out, "w") as f:
    f.write("// CT40.A9.Solari.embedded.js -- GENERATED by CT40.A9.Solari.build_embedded.py; do not hand-edit.\n")
    f.write("// Fallback copy of the JSON files and clack sample for when the page is opened as a local file.\n")
    f.write("window.SOLARI_EMBEDDED = {\n")
    f.write("  fields: " + json.dumps(fields) + ",\n")
    f.write("  schedule: " + json.dumps(schedule) + ",\n")
    f.write("  soundBase64: \"" + wav_b64 + "\"\n};\n")
print(f"wrote {out} ({os.path.getsize(out)} bytes)")
